const SCALE = .12, TAU = Math.PI * 2;
export const KID_GOKU_PARTS = Object.freeze(['hair', 'face', 'eyes-smile', 'blue-vest', 'arms-wristbands', 'wide-trousers', 'white-sash', 'power-pole', 'boots-tail']);
export const KID_GOKU_EYES = Object.freeze([
  Object.freeze({ x: -3.36, y: 74.52, rx: 2.76, ry: 3.24 }),
  Object.freeze({ x: 3.84, y: 74.64, rx: 2.88, ry: 3.12 }),
]);
export function isKidGokuEye(part, x, y) {
  if (part !== 2) return false;
  const left = KID_GOKU_EYES[0], right = KID_GOKU_EYES[1];
  return ((x - left.x) / left.rx) ** 2 + ((y - left.y) / left.ry) ** 2 <= 1.04
    || ((x - right.x) / right.rx) ** 2 + ((y - right.y) / right.ry) ** 2 <= 1.04;
}
const stroke = (points, color, weight = 1, z = 3) => ({ points: points.map(([x, y, depth]) => [(x - 245) * SCALE, 108 - y * SCALE, depth ?? z]), color, weight });
const arc = (x, y, rx, ry, color, weight = 1, z = 3, start = 0, end = TAU) => stroke(Array.from({ length: 65 }, (_, i) => { const a = start + (end - start) * i / 64; return [x + Math.cos(a) * rx, y + Math.sin(a) * ry]; }), color, weight, z);

